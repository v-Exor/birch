import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
const browser = await chromium.launch({channel:'chrome'});
const page = await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
await page.goto('http://127.0.0.1:4174/lab-02/');
await page.waitForFunction(()=>document.querySelector('#process-status').textContent.includes('Complete') || !document.querySelector('#error-message').hidden,{},{timeout:65000});
console.log(JSON.stringify(await page.evaluate(()=>({engine:document.querySelector('#engine-status').textContent,version:document.querySelector('#engine-status').title,status:document.querySelector('#process-status').textContent,error:document.querySelector('#error-message').textContent,width:document.documentElement.scrollWidth,viewport:innerWidth})),null,2));
await mkdir('artifacts',{recursive:true});
await page.screenshot({path:'artifacts/desktop-home.png'});
await page.locator('#experiments').scrollIntoViewIfNeeded();
await page.screenshot({path:'artifacts/desktop-experiment.png'});
await page.screenshot({path:'artifacts/desktop-full.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.goto('http://127.0.0.1:4174/lab-02/');
await page.waitForFunction(()=>document.querySelector('#process-status').textContent.includes('Complete'),{},{timeout:65000});
await page.screenshot({path:'artifacts/mobile-home.png'});
await page.locator('#experiments').scrollIntoViewIfNeeded();
await page.screenshot({path:'artifacts/mobile-experiment.png'});
console.log(JSON.stringify({errors,mobile:await page.evaluate(()=>({width:document.documentElement.scrollWidth,viewport:innerWidth}))}));
await writeFile('artifacts/console-errors.json',JSON.stringify(errors,null,2));
await browser.close();
if(errors.length)process.exitCode=1;
